-- ============================================================
-- Esquema PostgreSQL (Supabase) del sistema de gestión de insumos,
-- incluidas las tablas y reglas de responsables (E4).
-- Es la única definición de la base: cualquier cambio de tablas se hace acá.
--
-- Es idempotente: se puede volver a ejecutar sin romper nada.
-- Se aplica con: node scripts/pg-esquema.js
-- ============================================================

CREATE TABLE IF NOT EXISTS proveedores (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre     TEXT        NOT NULL,
  contacto   TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS insumos (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       TEXT        NOT NULL,
  tipo         TEXT        NOT NULL CHECK (tipo IN ('plantilla','fondo','cierre','hebilla')),
  color        TEXT,
  stock_minimo INTEGER     NOT NULL DEFAULT 0,
  proveedor_id INTEGER     REFERENCES proveedores(id) ON DELETE SET NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- talle NULL = stock sin talle. NULLS NOT DISTINCT impide dos filas
-- "sin talle" para el mismo insumo.
CREATE TABLE IF NOT EXISTS insumo_stock (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  insumo_id INTEGER NOT NULL REFERENCES insumos(id) ON DELETE CASCADE,
  talle     TEXT,
  stock     INTEGER NOT NULL DEFAULT 0,
  UNIQUE NULLS NOT DISTINCT (insumo_id, talle)
);

CREATE TABLE IF NOT EXISTS insumo_talles (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  insumo_id INTEGER NOT NULL REFERENCES insumos(id) ON DELETE CASCADE,
  talle     TEXT    NOT NULL,
  UNIQUE (insumo_id, talle)
);

CREATE TABLE IF NOT EXISTS productos (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       TEXT        NOT NULL,
  plantilla_id INTEGER     NOT NULL REFERENCES insumos(id),
  fondo_id     INTEGER     NOT NULL REFERENCES insumos(id),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS producto_talles (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
  talle       TEXT    NOT NULL,
  UNIQUE (producto_id, talle)
);

CREATE TABLE IF NOT EXISTS producto_accesorios (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id      INTEGER NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
  insumo_id        INTEGER NOT NULL REFERENCES insumos(id),
  cantidad_por_par INTEGER NOT NULL DEFAULT 1,
  UNIQUE (producto_id, insumo_id)
);

CREATE TABLE IF NOT EXISTS ordenes_produccion (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descripcion  TEXT,
  estado       TEXT        NOT NULL DEFAULT 'borrador' CHECK (estado IN ('borrador','confirmada','cancelada')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  confirmed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS detalle_orden (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  orden_id      INTEGER NOT NULL REFERENCES ordenes_produccion(id) ON DELETE CASCADE,
  producto_id   INTEGER NOT NULL REFERENCES productos(id),
  talle         TEXT    NOT NULL,
  cantidad      INTEGER NOT NULL DEFAULT 1,
  numero_pedido INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS pedidos_proveedor (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  proveedor_id     INTEGER     NOT NULL REFERENCES proveedores(id),
  estado           TEXT        NOT NULL DEFAULT 'borrador' CHECK (estado IN ('borrador','enviado','recibido','cancelado')),
  mensaje_whatsapp TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  recibido_at      TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS detalle_pedido_proveedor (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id INTEGER NOT NULL REFERENCES pedidos_proveedor(id) ON DELETE CASCADE,
  insumo_id INTEGER NOT NULL REFERENCES insumos(id),
  talle     TEXT,
  cantidad  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS movimientos_stock (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  insumo_id       INTEGER     NOT NULL REFERENCES insumos(id),
  talle           TEXT,
  tipo            TEXT        NOT NULL CHECK (tipo IN ('ingreso','egreso','ajuste','consumo_orden','ingreso_pedido')),
  cantidad        INTEGER     NOT NULL,
  referencia_tipo TEXT,
  referencia_id   INTEGER,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------- E4: responsables ----------

CREATE TABLE IF NOT EXISTS responsables (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug       TEXT        NOT NULL UNIQUE,
  nombre     TEXT        NOT NULL,
  activo     INTEGER     NOT NULL DEFAULT 1 CHECK (activo IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- insumo_id como clave primaria: un insumo tiene como máximo un responsable
CREATE TABLE IF NOT EXISTS insumo_responsable (
  insumo_id      INTEGER     PRIMARY KEY REFERENCES insumos(id) ON DELETE CASCADE,
  responsable_id INTEGER     NOT NULL REFERENCES responsables(id),
  asignado_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_insumo_responsable_responsable ON insumo_responsable(responsable_id);

CREATE TABLE IF NOT EXISTS pedido_responsable (
  pedido_id      INTEGER     PRIMARY KEY REFERENCES pedidos_proveedor(id) ON DELETE CASCADE,
  responsable_id INTEGER     NOT NULL REFERENCES responsables(id),
  asignado_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_pedido_responsable_responsable ON pedido_responsable(responsable_id);

CREATE TABLE IF NOT EXISTS schema_migraciones (
  id          TEXT        PRIMARY KEY,
  aplicada_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

