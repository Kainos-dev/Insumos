-- Reglas de responsables (migración 003_reglas_responsables).
-- Los mensajes de error son los mismos que espera el código.

CREATE OR REPLACE FUNCTION fn_ir_bloquear_con_pedidos_abiertos() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.responsable_id IS DISTINCT FROM OLD.responsable_id AND EXISTS (
      SELECT 1 FROM detalle_pedido_proveedor d
      JOIN pedidos_proveedor p ON p.id = d.pedido_id AND p.estado IN ('borrador','enviado')
      JOIN pedido_responsable pr ON pr.pedido_id = p.id
      WHERE d.insumo_id = NEW.insumo_id AND pr.responsable_id <> NEW.responsable_id
    ) THEN
      RAISE EXCEPTION 'REASIGNACION_CON_PEDIDOS_ABIERTOS';
    END IF;
    RETURN NEW;
  END IF;

  -- DELETE
  IF EXISTS (
    SELECT 1 FROM detalle_pedido_proveedor d
    JOIN pedidos_proveedor p ON p.id = d.pedido_id AND p.estado IN ('borrador','enviado')
    JOIN pedido_responsable pr ON pr.pedido_id = p.id
    WHERE d.insumo_id = OLD.insumo_id
  ) THEN
    RAISE EXCEPTION 'REASIGNACION_CON_PEDIDOS_ABIERTOS';
  END IF;
  RETURN OLD;
END $$;

DROP TRIGGER IF EXISTS trg_ir_reasignacion_abiertos ON insumo_responsable;
CREATE TRIGGER trg_ir_reasignacion_abiertos
  BEFORE UPDATE OF responsable_id ON insumo_responsable
  FOR EACH ROW EXECUTE FUNCTION fn_ir_bloquear_con_pedidos_abiertos();

DROP TRIGGER IF EXISTS trg_ir_desasignacion_abiertos ON insumo_responsable;
CREATE TRIGGER trg_ir_desasignacion_abiertos
  BEFORE DELETE ON insumo_responsable
  FOR EACH ROW EXECUTE FUNCTION fn_ir_bloquear_con_pedidos_abiertos();

CREATE OR REPLACE FUNCTION fn_pr_inmutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'PEDIDO_RESPONSABLE_INMUTABLE';
END $$;

DROP TRIGGER IF EXISTS trg_pr_inmutable ON pedido_responsable;
CREATE TRIGGER trg_pr_inmutable
  BEFORE UPDATE ON pedido_responsable
  FOR EACH ROW EXECUTE FUNCTION fn_pr_inmutable();

-- ---------- Seguridad ----------
-- Supabase expone el esquema public por su API REST. La app se conecta
-- directo a PostgreSQL, así que se activa RLS sin políticas: la API queda
-- sin acceso a estas tablas y la app (dueña de las tablas) no se ve afectada.
DO $$
DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'proveedores','insumos','insumo_stock','insumo_talles','productos',
    'producto_talles','producto_accesorios','ordenes_produccion','detalle_orden',
    'pedidos_proveedor','detalle_pedido_proveedor','movimientos_stock',
    'responsables','insumo_responsable','pedido_responsable','schema_migraciones'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
